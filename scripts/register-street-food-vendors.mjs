function generateVendorLogo(name, id) {
  const words = name.replace(/[^a-zA-Z\s]/g, '').trim().split(/\s+/);
  const initials = words.length === 1 ? words[0].slice(0, 2).toUpperCase() : (words[0][0] + words[1][0]).toUpperCase();
  const gradStart = '#94381c';
  const gradEnd = '#432818';
  const accent = '#fce588';
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" width="200" height="200">
  <defs>
    <linearGradient id="brandGrad_${id}" x1="0%" y1="0%" x2="100%" y2="100%">
      <stop offset="0%" stop-color="${gradStart}"/>
      <stop offset="100%" stop-color="${gradEnd}"/>
    </linearGradient>
    <filter id="shadow_${id}" x="-10%" y="-10%" width="120%" height="120%">
      <feDropShadow dx="0" dy="2" stdDeviation="2.5" flood-opacity="0.35"/>
    </filter>
  </defs>
  <rect x="4" y="4" width="92" height="92" rx="26" fill="url(#brandGrad_${id})" stroke="${accent}" stroke-width="2.5" filter="url(#shadow_${id})"/>
  <rect x="9" y="9" width="82" height="82" rx="21" fill="none" stroke="${accent}" stroke-width="1" stroke-dasharray="3 3" opacity="0.45"/>
  <circle cx="50" cy="38" r="14" stroke="${accent}" stroke-width="2" fill="none" opacity="0.7"/>
  <path d="M44 30 L44 46 M56 30 L56 46 M42 30 C42 35 46 35 46 30" stroke="${accent}" stroke-width="2" stroke-linecap="round"/>
  <text x="50" y="76" text-anchor="middle" font-family="system-ui, -apple-system, sans-serif" font-weight="900" font-size="15" fill="#ffffff" letter-spacing="1.5">${initials}</text>
  <text x="50" y="87" text-anchor="middle" font-family="system-ui, -apple-system, sans-serif" font-weight="800" font-size="6.5" fill="${accent}" letter-spacing="2">STREET FOOD</text>
</svg>`;
  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
}

async function run() {
  console.log(`Starting registration of ${STREET_FOOD_VENDORS.length} authentic Gorakhpur local street food vendors...`);

  // Ensure every vendor has logoUrl
  for (const v of STREET_FOOD_VENDORS) {
    if (!v.logoUrl) {
      v.logoUrl = generateVendorLogo(v.name, v.id);
    }
  }

  // 1. Check existing in Supabase
  const { data: existing, error: errFetch } = await supabase.from('restaurants').select('id');
  if (errFetch) {
    console.error('Error querying Supabase:', errFetch.message);
  } else {
    console.log(`Current restaurants count in Supabase: ${existing.length}`);
  }

  // 2. Format rows for Supabase insertion
  const rows = STREET_FOOD_VENDORS.map((r) => ({
    id: r.id,
    name: r.name,
    area: r.area,
    city: r.city,
    description: r.description,
    categories: r.categories,
    cuisines: r.cuisines,
    popular_dishes: r.popularDishes,
    cost_for_two: r.costForTwo,
    average_rating: r.averageRating,
    review_count: r.reviewCount,
    image_url: r.imageUrl,
    logo_url: r.logoUrl,
    is_demo: false,
    phone: r.whatsappPhone || r.phone,
    address: r.address,
    open_time: r.openTime,
    close_time: r.closeTime,
    open_days: r.openDays,
    diet: r.diet,
    status: r.status,
    owner_name: r.ownerName,
    owner_email: r.ownerEmail,
    facilities: r.facilities,
    menu: r.menu,
    ratings_breakdown: r.ratingsBreakdown,
    price_range: r.priceRange,
    distance_km: r.distanceKm,
    updated_at: new Date().toISOString()
  }));

  const { error: upsertErr } = await supabase.from('restaurants').upsert(rows, { onConflict: 'id' });
  if (upsertErr) {
    console.error('Error upserting street food vendors to Supabase:', upsertErr);
  } else {
    console.log(`Successfully upserted ${rows.length} street food vendors into Supabase database!`);
  }

  // 3. Update local src/data/gorakhpurRestaurants.ts
  const filePath = path.resolve('src/data/gorakhpurRestaurants.ts');
  const fileContent = fs.readFileSync(filePath, 'utf-8');

  // Check which vendors aren't in gorakhpurRestaurants.ts yet
  const newVendors = STREET_FOOD_VENDORS.filter((v) => !fileContent.includes(`"id": "${v.id}"`));
  console.log(`New vendors to append to gorakhpurRestaurants.ts: ${newVendors.length}`);

  if (newVendors.length > 0) {
    // Append them right before the closing "];"
    const lastBracketIdx = fileContent.lastIndexOf('];');
    if (lastBracketIdx !== -1) {
      const jsonSnippet = ',\n' + JSON.stringify(newVendors, null, 2).slice(1, -1).trim() + '\n';
      const updatedContent = fileContent.slice(0, lastBracketIdx).trimEnd() + jsonSnippet + '];\n';
      fs.writeFileSync(filePath, updatedContent, 'utf-8');
      console.log('Successfully updated src/data/gorakhpurRestaurants.ts!');
    }
  }
}

run();
